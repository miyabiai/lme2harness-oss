import { describe, expect, it } from "vitest";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { findHarnessInstall, parseWranglerToml } from "../src/harness/install.js";
import { loadDotEnv, setDotEnvValue } from "../src/config.js";

const TOML = `# Generated by create-line-harness.
name = "acme-line-harness"
account_id = "acc123"

[[d1_databases]]
binding = "DB"
database_name = "acme-line-harness"
database_id = "d1-uuid"

[[r2_buckets]]
bucket_name = "acme-images"

[vars]
WORKER_PUBLIC_URL = "https://acme-line-harness.acme.workers.dev"
ADMIN_PUBLIC_URL = "https://acme-admin.pages.dev"
`;

function makeInstall(root: string, withConfig: boolean): string {
  const dir = join(root, ".line-harness");
  mkdirSync(join(dir, "apps", "worker"), { recursive: true });
  writeFileSync(join(dir, "apps", "worker", "wrangler.toml"), TOML);
  if (withConfig) {
    writeFileSync(
      join(dir, ".line-harness-config.json"),
      JSON.stringify({ workerName: "acme-line-harness", d1DatabaseName: "acme-line-harness", d1DatabaseId: "d1-uuid", workerPublicUrl: "https://from-config.workers.dev", installedVersion: "0.24.1", apiKey: "lh_test_key_1234" }),
    );
  }
  return dir;
}

describe("L Harness の導入フォルダ検出", () => {
  it("wrangler.toml から D1・Worker 名・公開 URL を読む", () => {
    const t = parseWranglerToml(TOML);
    expect(t).toMatchObject({ workerName: "acme-line-harness", accountId: "acc123", d1DatabaseName: "acme-line-harness", d1DatabaseId: "d1-uuid", workerUrl: "https://acme-line-harness.acme.workers.dev" });
  });

  it("~/.line-harness の .line-harness-config.json を優先して読む", () => {
    const root = mkdtempSync(join(tmpdir(), "l2h-"));
    makeInstall(root, true);
    const work = join(root, "work");
    mkdirSync(work);
    const hit = findHarnessInstall(undefined, work, root);
    expect(hit?.workerUrl).toBe("https://from-config.workers.dev");
    expect(hit?.d1DatabaseId).toBe("d1-uuid");
    expect(hit?.version).toBe("0.24.1");
    expect(hit?.apiKey).toBe("lh_test_key_1234");
  });

  it("設定ファイルに API キーが無ければ apiKey は undefined", () => {
    const root = mkdtempSync(join(tmpdir(), "l2h-"));
    const dir = makeInstall(root, false);
    expect(findHarnessInstall(dir, root, "")?.apiKey).toBeUndefined();
  });

  it("設定ファイルが無くても wrangler.toml だけで見つかる", () => {
    const root = mkdtempSync(join(tmpdir(), "l2h-"));
    const dir = makeInstall(root, false);
    const hit = findHarnessInstall(dir, root, "");
    expect(hit?.d1DatabaseName).toBe("acme-line-harness");
    expect(hit?.source.endsWith("wrangler.toml")).toBe(true);
  });

  it("見つからなければ null", () => {
    const root = mkdtempSync(join(tmpdir(), "l2h-"));
    expect(findHarnessInstall(undefined, root, root)).toBeNull();
  });
});

describe(".env の1項目書き換え", () => {
  it("他の行とコメントを残して値だけ入れる", () => {
    const dir = mkdtempSync(join(tmpdir(), "l2h-"));
    writeFileSync(join(dir, ".env"), "# コメント\nLME_API_KEY=abc\nHARNESS_API_KEY=\n");
    setDotEnvValue("HARNESS_API_KEY", "secret-1", dir);
    setDotEnvValue("NEW_KEY", "v", dir);
    const text = readFileSync(join(dir, ".env"), "utf8");
    expect(text.startsWith("# コメント\n")).toBe(true);
    expect(loadDotEnv(dir)).toMatchObject({ LME_API_KEY: "abc", HARNESS_API_KEY: "secret-1", NEW_KEY: "v" });
  });
});
